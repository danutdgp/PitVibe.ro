-- Zone locale cu prezență declarată și temporară.
create table public.local_zones (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name text not null unique check (char_length(name) between 2 and 60),
  description text not null default '' check (char_length(description) <= 160),
  sort_order integer not null default 0,
  active boolean not null default true
);

create table public.zone_checkins (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  zone_id bigint not null references public.local_zones(id) on delete cascade,
  checked_in_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '2 hours'),
  constraint zone_checkin_lifetime check (expires_at > checked_in_at and expires_at <= checked_in_at + interval '2 hours 5 minutes')
);

create index zone_checkins_active_idx on public.zone_checkins(zone_id, expires_at desc);

